"""食材名 → 过敏原 的**隐性来源**映射（docs/12 §3.5，阶段零）。

## 为什么必须有这张表

`Recipe.all_allergen_names()` 的兜底原本是"食材名里包含标签词就命中"。实测 171 个食材名里：

| 标签 | 在食材名中出现 | 能否兜底 |
|---|---|---|
| 蛋 | 11 次 | 可以 |
| 花生 / 奶 | 各 1 次 | 勉强 |
| **海鲜 / 坚果 / 大豆 / 麸质 / 芝麻** | **各 0 次** | **不能** |

因为食材名写的是「蚝油」「生抽」「蒸鱼豉油」，**永远不会出现「海鲜」二字**。
于是这 5 个标签完全依赖 `allergens` 字段被人工填对，而 19/38 道菜的该字段是空的 ——
实测「蚝油生菜」（食材含蚝油＝牡蛎）对海鲜过敏的用户**不会被排除**。

这直接违反 `docs/05` 的不变量 R6「忌口永不妥协」，而且**漏检机会随条目数线性增长**：
扩到 100 道就是多 60 多次漏标机会。所以修表在前、扩库在后（`docs/12` §4 阶段零）。

## 标注规则（宁可多排掉一道，也不能漏）

**只要配方里存在"常见含该过敏原"的加工调味料，就标该过敏原。**
安全优先于选择面：多标一次，用户少吃一道菜；漏标一次，用户可能进医院。
这与 05 R6 一致，也是 `docs/12` §3.5 给的口径（它把「番茄酱/淀粉 → 麸质」也列进来了）。

代价要明说：标注变严之后**候选池会变小**（尤其麸质与大豆），
所以这张表的直接后果是"阶段一扩库更迫切"，而不是"标注完就没事了"。

## 收录原则

只收**含义明确**的词。含糊的（例如单写「淀粉」）不靠这张表兜 —— 而是回到数据层把话说清楚
（`淀粉` → `玉米淀粉`），因为映射写宽了会误伤、写窄了会漏检，而数据层可以写准确。
"""
from __future__ import annotations

from typing import Iterable

# 过敏原标签 → 常见含该过敏原的食材/调味料关键词
# 关键词按"子串包含"匹配（`生抽` 命中「生抽」「薄盐生抽」）。
#
# 刻意**不**收的词（收了就是误伤，会让用户白白少一道菜）：
# - 光秃秃的「鱼」：会命中「鱼香肉丝」（没有鱼）；
# - 光秃秃的「豆」：会命中「土豆」「红豆」「四季豆」（都不是大豆）；
# - 光秃秃的「面」/「麦」：会命中「玉米面」「荞麦」（都不含麸质）→ 只收「小麦/大麦/麦芽/燕麦/麦片」；
# - 「紫菜」「海带」「裙带菜」：是藻类，不属于鱼类/甲壳类/软体类，海鲜过敏通常不含它们；
# - 「淀粉」：可能是玉米/土豆淀粉（不含麸质），含义不明确 → 回到数据层把写法改准确；
# - 「花生」不进「坚果」：`ALLERGENS` 里两者是分开的两个标签，混在一起会让"只对花生过敏"的人
#   连核桃也吃不到。
HIDDEN_ALLERGENS: dict[str, tuple[str, ...]] = {
    "海鲜": ("蚝油", "鱼露", "虾", "蟹", "干贝", "瑶柱", "蒸鱼豉油", "海鲜酱", "鲍汁",
             "沙茶", "木鱼花", "鱼豆腐", "鱼丸", "鱼饼"),
    "大豆": ("生抽", "老抽", "酱油", "味极鲜", "豆豉", "豆瓣", "黄豆", "豆酱", "豆腐",
             "豆浆", "豆皮", "腐竹", "毛豆", "腐乳", "豆干"),
    "麸质": ("面粉", "面条", "挂面", "面筋", "面包", "馒头", "饺子皮", "馄饨皮", "甜面酱",
             "黄酱", "生抽", "老抽", "酱油", "味极鲜", "豆瓣", "豆酱", "蒸鱼豉油", "啤酒",
             "番茄酱", "小麦", "大麦", "麦芽", "燕麦", "麦片", "方便面", "意面", "拉面", "乌冬"),
    "芝麻": ("香油", "麻酱", "芝麻", "芝麻油"),
    "坚果": ("腰果", "杏仁", "核桃", "松子", "开心果", "榛子", "巴旦木", "夏威夷果"),
    "蛋": ("鸡蛋", "鸭蛋", "鹌鹑蛋", "皮蛋", "咸蛋", "蛋清", "蛋黄", "沙拉酱", "蛋黄酱"),
    "奶": ("牛奶", "奶油", "黄油", "奶酪", "芝士", "起司", "炼乳", "酸奶", "奶粉"),
    "花生": ("花生", "花生米", "花生酱"),
}


def allergens_in_ingredient(name: str) -> set[str]:
    """这个食材名的**隐性**过敏原（只看名字，不看 `allergens` 字段）。"""
    got: set[str] = set()
    text = name or ""
    for tag, keywords in HIDDEN_ALLERGENS.items():
        if any(kw in text for kw in keywords):
            got.add(tag)
    return got


def hidden_allergens(dish: str = "", ingredients: Iterable[str] = ()) -> set[str]:
    """一道菜的隐性过敏原：食材名 + 菜名（有的菜名直接写了主料，例如「蒜蓉粉丝蒸虾」）。

    菜名也看，是因为"菜名里的虾"和"食材里的虾"对用户是同一件事；
    但**判断依据仍然是字面匹配**，不猜菜系（与 `core.in_meal_pool` 同一条原则）。
    """
    got = allergens_in_ingredient(dish)
    for ing in ingredients:
        got |= allergens_in_ingredient(ing)
    return got
